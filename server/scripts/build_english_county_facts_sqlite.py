def validate_facts(entities: list[dict]) -> None:
    entity_names = {e["name"] for e in entities}
    fact_names = set(COUNTY_FACTS.keys())
    if entity_names != fact_names:
        missing = entity_names - fact_names
        extra = fact_names - entity_names
        raise ValueError(f"County mismatch! missing={missing}, extra={extra}")

    # Verify strict symmetry of borders_county
    for name, info in COUNTY_FACTS.items():
        for neighbor in info["borders_county"]:
            if neighbor not in COUNTY_FACTS:
                raise ValueError(f"{name} references unknown neighbor {neighbor}")
            if neighbor == name:
                raise ValueError(f"{name} lists itself as a neighbor")
            if name not in COUNTY_FACTS[neighbor]["borders_county"]:
                raise ValueError(
                    f"Asymmetric border: {name} -> {neighbor} exists, but {neighbor} -> {name} does not"
                )


def build() -> None:
    payload = json.loads(ENTITIES_JSON.read_text(encoding="utf-8"))
    entities = payload["entities"]
    validate_facts(entities)

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    # Write CSV
    with CSV_PATH.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "name", "county_town", "region", "latitude", "longitude"])
        for entity in entities:
            fact = COUNTY_FACTS[entity["name"]]
            writer.writerow([
                entity["id"],
                entity["name"],
                fact["county_town"],
                fact["region"],
                entity["latitude"],
                entity["longitude"],
            ])

    # Build SQLite
    if SQLITE_PATH.exists():
        SQLITE_PATH.unlink()

    schema = SCHEMA_SQL.read_text(encoding="utf-8")
    with sqlite3.connect(SQLITE_PATH) as conn:
        conn.executescript(schema)
        for entity in entities:
            cid = int(entity["id"])
            name = str(entity["name"])
            fact = COUNTY_FACTS[name]
            conn.execute(
                """
                INSERT INTO english_counties (
                    id, name, county_town, region, is_coastal, is_metropolitan,
                    population, area_km2, latitude, longitude
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    cid,
                    name,
                    fact["county_town"],
                    fact["region"],
                    int(fact["is_coastal"]),
                    int(fact["is_metropolitan"]),
                    int(fact["population"]),
                    float(fact["area_km2"]),
                    float(entity["latitude"]),
                    float(entity["longitude"]),
                ),
            )
            for neighbor in sorted(set(fact["borders_county"])):
                conn.execute(
                    "INSERT INTO english_county_borders_counties (county_id, border_county_name) VALUES (?, ?)",
                    (cid, neighbor),
                )
            for country in sorted(set(fact["borders_country"])):
                conn.execute(
                    "INSERT INTO english_county_borders_countries (county_id, country_name) VALUES (?, ?)",
                    (cid, country),
                )
            for water in sorted(set(fact["water_access"])):
                conn.execute(
                    "INSERT INTO english_county_water_access (county_id, water_body) VALUES (?, ?)",
                    (cid, water),
                )
            for river in sorted(set(fact["major_rivers"])):
                conn.execute(
                    "INSERT INTO english_county_major_rivers (county_id, river_name) VALUES (?, ?)",
                    (cid, river),
                )
            for city in sorted(set(fact["major_cities"])):
                conn.execute(
                    "INSERT INTO english_county_major_cities (county_id, city_name) VALUES (?, ?)",
                    (cid, city),
                )
            for label in sorted(set(fact["regional_labels"])):
                conn.execute(
                    "INSERT INTO english_county_regional_labels (county_id, label) VALUES (?, ?)",
                    (cid, label),
                )
        conn.commit()
    print(f"Built {SQLITE_PATH} and {CSV_PATH} with {len(entities)} English ceremonial counties.")


if __name__ == "__main__":
    build()
